/**
 * Generates the register documents from the same data the app uses, so the
 * docs cannot drift from the code: SOURCE_REGISTER.md, FEATURE_MATRIX.md,
 * PARAMETERS.md.   npm run docs
 */
import { writeFileSync } from 'node:fs';
import { SOURCES, DISCREPANCIES } from '../src/config/sources';
import { FEATURE_MATRIX } from '../src/ui/features';
import { PARAM_DEFS } from '../src/config/registry';

const esc = (s: string) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const head = (t: string) => `<!-- generated by scripts/gen_docs.ts; edit the source data, not this file -->\n# ${t}\n\n`;

let src = head('Source register');
src += 'All official documents were downloaded from the Mitsubishi Electric UK library on 2026-10-27. Every parameter marked *sourced* or *digitised* cites one of these ids with a page (see PARAMETERS.md). Secondary sources are used only as plausibility cross-checks, never as model inputs.\n\n';
src += '| Id | Kind | Title | Doc no. / revision | Covers |\n|---|---|---|---|---|\n';
for (const s of Object.values(SOURCES)) src += `| ${s.id} | ${s.kind} | [${esc(s.title)}](${s.url}) | ${esc(s.docNo)} · ${esc(s.revision)} | ${esc(s.covers)}${s.note ? ' — ' + esc(s.note) : ''} |\n`;
src += '\n## Discrepancies and how they were resolved\n\n| Id | Field | Resolution |\n|---|---|---|\n';
for (const d of DISCREPANCIES) src += `| ${d.id} | ${esc(d.field)} | ${esc(d.detail)} |\n`;
src += '\nMachine-readable form: `src/config/sources.ts` (shown in the app under *Assumptions & sources*).\n';
writeFileSync('SOURCE_REGISTER.md', src);

let fm = head('Feature matrix: original product operation vs. simulator experiments');
fm += '"Original" means the function is documented for MSZ-AP35VGK / MUZ-AP35VG in the cited manual. Everything in the experiment layer is labelled as such in the app and never presented as a product function.\n\n';
fm += '| Function | On the original unit | Source | In this app |\n|---|---|---|---|\n';
for (const f of FEATURE_MATRIX) fm += `| ${esc(f.fn)} | ${esc(f.original)} | ${esc(f.source)} | ${esc(f.app)} |\n`;
writeFileSync('FEATURE_MATRIX.md', fm);

const counts: Record<string, number> = {};
for (const p of PARAM_DEFS) counts[p.status] = (counts[p.status] ?? 0) + 1;
let pr = head('Parameter register');
pr += 'Status meanings: **sourced** = read from an official document (page cited); **digitised** = read off a published curve; **calibrated** = fitted to published data (see CALIBRATION_GUIDE.md); **assumed** = engineering assumption, not published; **supplied** = scenario input; **computed** = derived.\n\n';
pr += 'Counts: ' + Object.entries(counts).map(([k, v]) => `${k} ${v}`).join(' · ') + '\n\n';
const groups = [...new Set(PARAM_DEFS.map((p) => p.group))];
for (const g of groups) {
  pr += `## ${g}\n\n| Key | Label | Value | Unit | Status | Origin | Range | Edit | Note |\n|---|---|---|---|---|---|---|---|---|\n`;
  for (const p of PARAM_DEFS.filter((x) => x.group === g)) pr += `| \`${p.key}\` | ${esc(p.label)} | ${+p.value.toPrecision(6)} | ${esc(p.unit)} | ${p.status} | ${esc(p.origin)} | ${p.range[0]}…${p.range[1]} | ${p.editable ?? 'model'} | ${esc(p.note)} |\n`;
  pr += '\n';
}
writeFileSync('PARAMETERS.md', pr);
console.log('Wrote SOURCE_REGISTER.md, FEATURE_MATRIX.md, PARAMETERS.md', counts);
